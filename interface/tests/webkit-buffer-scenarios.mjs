const helpers = `
const checks=[];
const check=(condition,name)=>{if(!condition)throw new Error(name);checks.push(name);};
const until=async predicate=>{const deadline=performance.now()+10000;while(!predicate()){if(performance.now()>deadline)throw new Error('Buffer UI readiness timed out');await new Promise(r=>setTimeout(r,20));}};
const button=label=>[...document.querySelectorAll('button')].find(item=>item.textContent.trim()===label);
const fixture=body=>window.webkit.messageHandlers.fixture.postMessage(body);
const size=()=>document.querySelector('[aria-label="Hardware buffer size"]');
const commands=async()=>(await fixture({operation:'commands'})).filter(c=>c.operation==='device-buffer');
await until(()=>button('Settings'));
`;
export const beforeBufferReload = `${helpers}
const envelope=await window.webkit.messageHandlers.loopz.postMessage({version:1,operation:'state'});
const device=envelope.inventory.devices.find(d=>d.uid==='phones');
Object.assign(device,{rate:48000,bufferFrames:512,minimumBufferFrames:32,maximumBufferFrames:1024});
envelope.inventory.devices.push({...device,uid:'input-hardware',name:'Input hardware',bufferFrames:128,maximumBufferFrames:512});
envelope.inventory.devices.push({...device,uid:'unused',name:'Unused hardware',minimumBufferFrames:256});
Object.assign(envelope.inventory,{devicesFresh:true,bufferSettingsAvailable:true,bufferSettingsPersistence:true,routingBufferSettings:true,routingBufferFrames:0,routingBufferDevices:['phones','input-hardware'],bufferPreferences:[]});
await fixture({operation:'replace-envelope',envelope});
const meter=()=>document.querySelector('[aria-label="Player channel 1 pre-gain meter"]');
const meterBefore=meter().getAttribute('aria-valuenow');
button('Settings').click();
await until(()=>size()?.selectedOptions[0]?.textContent==='Mixed buffer sizes');
envelope.snapshot.runtime.devices[0].sources[0].meter.peak[0]=0.01;
await fixture({operation:'replace-envelope',envelope});
await new Promise(r=>setTimeout(r,200));
check(meter().getAttribute('aria-valuenow')===meterBefore,'Meters behind the modal stay still while live state continues updating');
check(size().selectedOptions[0].textContent==='Mixed buffer sizes','Different actual buffers are shown truthfully');
check([...size().options].slice(1).map(o=>+o.value).join(',')==='32,64,128,256,512','Choices use the common range of used devices only');
check([...size().options].find(o=>o.value==='64').textContent.includes('1.33 ms target/buffer · Balanced'),'The selector labels target buffer latency and the balanced choice');
check(!document.querySelector('[aria-label="Hardware buffer audio device"]')&&!button('Apply buffer size'),'One setting has no device picker or Apply button');
check((await commands()).length===0,'Opening Settings performs no hardware operation');
envelope.inventory.devicesFresh=false;
await fixture({operation:'replace-envelope',envelope});
await until(()=>size().disabled);
check(true,'Stale metadata disables changes');
envelope.inventory.devicesFresh=true;
envelope.inventory.bufferSettingsAvailable=false;
await fixture({operation:'replace-envelope',envelope});
await until(()=>size().disabled);
check(true,'Disconnected Engine disables changes');
envelope.inventory.bufferSettingsAvailable=true;
await fixture({operation:'replace-envelope',envelope});
await until(()=>!size().disabled);
size().value='32';size().dispatchEvent(new Event('change',{bubbles:true}));
await until(()=>document.querySelector('[role="alert"]')?.textContent.includes('synthetic bridge'));
check((await commands()).length===1,'Changing the selector sends exactly one immediate request');
check(JSON.stringify((await commands())[0].buffer)==='{"frames":32}','The request targets all used hardware rather than a selected UID');
check(size().value==='0'&&!size().disabled,'Rejected changes keep the actual value and release busy state');
await new Promise(r=>setTimeout(r,250));
check((await commands()).length===1,'Rejected choices are not silently retried by the UI');
envelope.inventory.simulateGlobalBuffers=true;
await fixture({operation:'replace-envelope',envelope});
size().value='32';size().dispatchEvent(new Event('change',{bubbles:true}));
await until(()=>size().value==='32'&&!size().disabled&&!document.querySelector('[role="alert"]'));
check((await commands()).length===2,'A subsequent selection applies successfully');
const current=await window.webkit.messageHandlers.loopz.postMessage({version:1,operation:'state'});
check(current.inventory.devices.filter(d=>['phones','input-hardware'].includes(d.uid)).every(d=>d.bufferFrames===32),'Both used endpoints receive the selection in the fixture');
check(current.inventory.devices.find(d=>d.uid==='unused').bufferFrames===512,'Unused hardware is unaffected');
button('Done').click();
await until(()=>!size());
await until(()=>meter().getAttribute('aria-valuenow')==='-40');
check(true,'Meters immediately resume at the latest signal when the modal closes');
const fillStyle=getComputedStyle(document.querySelector('.lz-level-fill'));
check(fillStyle.transitionProperty==='transform','Visible meter smoothing animates only composited transforms');
check(parseFloat(fillStyle.transitionDuration)<=0.08,'Meter release stays below 80 milliseconds');
check(getComputedStyle(document.querySelector('.lz-level-peak')).transitionProperty==='transform','The peak marker also uses transform smoothing');
return {checks};
`;
export const afterBufferReload = `${helpers}
button('Settings').click();
await until(()=>size()?.value==='32');
check((await commands()).length===2,'Reload keeps the saved choice without sending another request');
check(document.querySelector('[role="dialog"]').textContent.includes('device reconnects'),'Automatic restoration is described');
for(const animation of document.querySelector('.modal-scrim').getAnimations({subtree:true}))animation.finish();
const dialog=document.querySelector('[role="dialog"]');
check(dialog.scrollWidth<=dialog.clientWidth,'Hardware controls fit the SingZ modal');
check(getComputedStyle(document.querySelector('.lz-level-fill')).transitionDuration==='0s','Meters do not animate continuously between updates');
check(getComputedStyle(document.querySelector('.lz-level-fill')).transform!=='none','Meter fill uses bounded transforms instead of changing its layout width');
check(getComputedStyle(document.querySelector('.lz-node')).backdropFilter==='none','Routing cards avoid repeated backdrop blur work');
return {checks};
`;
